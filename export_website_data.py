"""
export_website_data.py - turn the ranked candidates into website/src/mlCandidates.js

The website's src/data.js has SAMPLE locations. This writes the real ML candidates in the same
shape, so they can be appended to LOCATIONS. Only real values are used; fields the analysis never
measured say 'Not analysed' (no invented place names, countries, climate or minerals).

Run from the project root:   python export_website_data.py
Then in TerraNova/src/data.js:  import { ML_CANDIDATES } from './mlCandidates.js';
                                export const LOCATIONS = [ ...yourSamples, ...ML_CANDIDATES ];
"""
import json
from pathlib import Path

from integration_layer import chatbot

OUT = Path(__file__).resolve().parent / "website_export" / "mlCandidates.js"
MARS_PALETTE = ["#2a1410", "#8a4a2b", "#d9925c"]


def to_website_location(records, index, meta):
    r = records[index]
    f = chatbot.record_facts(records, index, meta)
    t = r["terrain_features"]
    return {
        "id": r["discovery_id"].lower(),
        "name": f"Terrain candidate {r['discovery_id'][-2:]}",
        "country": "Coordinates only (no place name in the data)",
        "flag": "📍",
        "lat": round(r["latitude"], 4), "lon": round(r["longitude"], 4),
        "type": "mars", "status": "candidate",
        "terrain": "Not characterised (only elevation-derived numbers were analysed)",
        "climate": "Not analysed", "mineral": "Not analysed",
        "feature": f"Ranked {index + 1} of {len(records)} by similarity to the average Mars terrain profile",
        "why": chatbot.explain_candidate(f),
        "line": f"Ranked {index + 1} of {len(records)}: similarity {f['similarity_score']} to the average Mars terrain profile.",
        "stats": [f"{t['elevation_m']:.0f} m", "Not analysed",
                  f"Slope {t['slope_deg']:.2f}°, relief {t['local_relief_m']:.0f} m"],
        "source": "NASADEM (6-tile sample) vs Mars MOLA; computational result, geological review pending",
        "palette": MARS_PALETTE,
        "similarity": f["similarity_score"],
    }


def main():
    records, meta = chatbot.load_records(), chatbot.load_metadata()
    items = [to_website_location(records, i, meta) for i in range(len(records))]
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("// Generated by export_website_data.py from the project's ranked candidates. Do not edit by hand.\n"
                   f"export const ML_CANDIDATES = {json.dumps(items, indent=2, ensure_ascii=False)};\n", encoding="utf-8")
    print(f"Wrote {len(items)} candidates to {OUT}")


if __name__ == "__main__":
    main()
